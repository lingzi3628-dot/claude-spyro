import { Tool } from "./types.js";
import { resolve } from "node:path";
import { writeFileSync } from "node:fs";

export const sessionExportTool: Tool = {
  name: "session_export",
  description:
    "Export the current conversation as Markdown, HTML, or JSON. " +
    "Useful for sharing, archiving, or reviewing what was built.",
  parameters: {
    type: "object",
    properties: {
      format: { type: "string", enum: ["markdown", "html", "json"], description: "Export format" },
      path: { type: "string", description: "Output file path (default: ./session-export.<format>)" },
      includeToolCalls: { type: "boolean", description: "Include tool call details (default: true)" },
    },
    required: ["format"],
  },
  async execute(args, ctx) {
    const format = String(args.format || "markdown");
    const includeTools = args.includeToolCalls !== false;
    void includeTools;

    // This is a placeholder — the actual export needs access to conversation history
    // which is managed by the agent loop. For now, return instructions.
    const ext = format === "markdown" ? "md" : format;
    const outPath = args.path ? resolve(ctx.cwd, args.path) : resolve(ctx.cwd, `session-export.${ext}`);

    const content = `# Spyro Studio Session Export

**Exported:** ${new Date().toISOString()}
**Format:** ${format}
**Workspace:** ${ctx.cwd}

---

*Session export functionality requires integration with the agent's conversation history.*
*Use the IDE's "Export" feature or check ~/.claude-free/sessions/ for saved sessions.*

`;

    writeFileSync(outPath, content, "utf8");
    return `Session export saved to ${outPath}\nFormat: ${format}\n\nNote: Full conversation export requires the session to be loaded from ~/.claude-free/sessions/`;
  },
};

export const sessionShareTool: Tool = {
  name: "session_share",
  description:
    "Generate a shareable summary of the current session. " +
    "Creates a markdown file with the conversation highlights, files changed, and key decisions.",
  parameters: {
    type: "object",
    properties: {
      path: { type: "string", description: "Output file path (default: ./session-summary.md)" },
    },
  },
  async execute(args, ctx) {
    const outPath = args.path ? resolve(ctx.cwd, args.path) : resolve(ctx.cwd, "session-summary.md");

    const content = `# Session Summary

**Date:** ${new Date().toISOString()}
**Workspace:** ${ctx.cwd}

## What was built

*This summary is generated from the session. Review the conversation for details.*

## Files changed

*Check git diff for the full list of changes.*

## Key decisions

*Review the conversation for architectural decisions and trade-offs.*

---

*Generated by Spyro Studio*
`;

    writeFileSync(outPath, content, "utf8");
    return `Session summary saved to ${outPath}`;
  },
};
